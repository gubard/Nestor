            );

            stringBuilder.AppendLine(
                $"{property.GetEntityValueName()} = {property.GetEntityTypeFullName()}edit.{property.Name},"
            );

            stringBuilder.AppendLine("UserId = userId,");
            stringBuilder.AppendLine("TransactionId = transactionId,");
            stringBuilder.AppendLine("CreatedAt = now,");
            stringBuilder.AppendLine("};");
            stringBuilder.AppendLine("}");
            stringBuilder.AppendLine();
        }

        stringBuilder.AppendLine(
            $"queries[i] = edit.{id.Name}.CreateUpdate{type.GetTableName()}Query(updates);"
        );

        stringBuilder.AppendLine("}");
        stringBuilder.AppendLine();
        stringBuilder.AppendLine("for(var i = 0; i < queries.Length; i++)");
        stringBuilder.AppendLine("{");
        stringBuilder.AppendLine("session.ExecuteNonQuery(queries[i]);");
        stringBuilder.AppendLine("}");
        stringBuilder.AppendLine();
        stringBuilder.AppendLine("if(isUseEvents)");
        stringBuilder.AppendLine("{");
        stringBuilder.AppendLine("session.ExecuteNonQuery(events.CreateInsertQuery());");
        stringBuilder.AppendLine("}");
        stringBuilder.AppendLine("}");
    }

