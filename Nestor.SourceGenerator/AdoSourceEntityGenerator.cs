    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var assemblyAttributes = context.CompilationProvider.Select(
            (compilation, _) =>
                compilation
                    .Assembly.GetAttributes()
                    .Where(x => x.AttributeClass?.Name == "AdoSourceEntity")
        );

        context.RegisterSourceOutput(
            assemblyAttributes,
            (spc, attributes) =>
            {
                try
                {
                    foreach (var attribute in attributes)
                    {
                        if (attribute.ConstructorArguments.Length != 2)
                        {
                            continue;
                        }

                        if (attribute.ConstructorArguments[0].Value is not INamedTypeSymbol type)
                        {
                            continue;
                        }

                        if (attribute.ConstructorArguments[1].Value is not string idName)
                        {
                            continue;
                        }

                        var stringBuilder = new CSharpStringBuilder(4);

                        var properties = type.GetMembers()
                            .OfType<IPropertySymbol>()
                            .Where(p =>
                                !p.IsStatic && p.SetMethod is not null && p.GetMethod is not null
                            )
                            .ToArray();

                        var id = properties.FirstOrDefault(x => x.Name == idName);

                        if (id is null)
                        {
                            continue;
                        }

                        stringBuilder.AppendLine("// <auto-generated />");
                        stringBuilder.AppendLine();
                        stringBuilder.AppendLine("#nullable enable");
                        stringBuilder.AppendLine();
                        stringBuilder.AppendLine("using System.Linq;");
                        stringBuilder.AppendLine("using Nestor.Db.Models;");
                        stringBuilder.AppendLine("using Gaia.Helpers;");
                        stringBuilder.AppendLine();
                        stringBuilder.AppendLine($"namespace {type.GetNamespace()};");
                        stringBuilder.AppendLine();

                        stringBuilder.AppendLine(
                            $"public static class {type.GetTableName()}SourceExt"
                        );

                        stringBuilder.AppendLine("{");
                        CreateAddMethod(stringBuilder, type, id, properties);
                        stringBuilder.AppendLine();
                        CreateAddMethodA(stringBuilder, type, id, properties);
                        stringBuilder.AppendLine();
                        CreateDeleteMethod(stringBuilder, type, id);
                        stringBuilder.AppendLine();
                        CreateDeleteMethodA(stringBuilder, type, id);
                        stringBuilder.AppendLine();
                        CreateEditMethod(stringBuilder, type, id, properties);
                        stringBuilder.AppendLine();
                        CreateEditMethodA(stringBuilder, type, id, properties);
                        stringBuilder.AppendLine();
                        CreateGetMethod(stringBuilder, type, id);
                        stringBuilder.AppendLine();
                        CreateGetMethodA(stringBuilder, type, id);
                        stringBuilder.AppendLine();
                        CreateExistsAMethod(stringBuilder, type, id);
                        stringBuilder.AppendLine();
                        CreateExistsMethod(stringBuilder, type, id);
                        stringBuilder.AppendLine("}");
                        var text = stringBuilder.ToString();
                        spc.AddSource($"{type}.{nameof(AdoSourceEntityGenerator)}.g.cs", text);
                    }
                }
                catch (Exception e)
                {
                    spc.AddSource($"{nameof(AdoSourceEntityGenerator)}.g.cs", e.ToString());
                }
            }
        );
    }

